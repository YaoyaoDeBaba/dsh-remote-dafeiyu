/**
 * handoff/prompt —— 「一键转生 / 一键分身」的**两段文本**。
 *
 * 为什么是两段：
 * 1. `injection` 发给**当前这个**会话（它的上下文里才有全部经过）；
 * 2. `firstPrompt` 发给**新建的**那个会话（它只看得见交接文档）。
 *
 * 关键判断：转生/分身的总结**必须由当事人自己写**。让另一个模型去读几十 MB 的日志重写，
 * 又贵又会丢掉"当时为什么这么定"的那点手感。所以注入的是一份写作指令，不是一份分析任务。
 *
 * 另一条纪律：交接文档里「已完成，不要重做」比「目标」更重要——接手者最容易犯的错
 * 不是看不懂目标，而是把已经干完的活重干一遍。
 *
 * ## 2026-11-17 重写（0.9.0-dafeiyu.107）：把「转交不全」当第一优先级
 *
 * 依据是 9 份历史交接文档的逐项体检，最狠的三条：
 * - 「后台在跑的东西」6/9 份完全没写 → 接手者重派已在跑的子代理、去改别人正在跑的环境；
 * - 「工作区状态」7/9 份没写 → 接手者凭"主线全绿"动手，实际工作区开着半截改动；
 * - 「长期记忆」5/9 份连小节都没有，还有同一教训写两处、两处口径不一样的。
 * 另有大量「跑通即可」「可以直接当起点」这类没有判据的含糊话。
 *
 * 所以这一版不是改语气，是加三道闸：
 * ① **动笔前先核对现场**（git / 后台任务 / 记忆库 / 版本），凭记忆写一定会漏；
 * ② **含糊话黑名单**——没有判据的"完成"不算完成；
 * ③ **写完的自查清单**（小节 + 长期记忆 + 指针），缺一条就打回去补。
 * 顺带修一个真 bug：转生分支原来把用户填的 `boundary` **整个丢掉了**
 * （面板有输入框、`start()` 也传了，但这里没用），现在两个种类都认。
 */

export type HandoffKind = 'rebirth' | 'branch'

/** 交接文档写完后，模型必须单独输出这一行；插件靠它在等文件的同时确认"真写完了"。 */
export const HANDOFF_MARKER = 'DAFEIYU_HANDOFF_OK'

export interface HandoffPlan {
  kind: HandoffKind
  /** 交接文档的绝对路径（插件指定，模型照抄）。 */
  filePath: string
  /** 分身必填：分支要干的活（用户原文）。转生选填：交接重点。 */
  note?: string
  /** 选填：不许碰的东西（两个种类都认）。 */
  boundary?: string
  /** 发起方（前世）的会话 id：来生要提问时靠它找对门（2026-11-17 收件箱）。 */
  parentSessionId?: string
  /** 结构判据补到上限仍不合格的缺口：带进首句，让来生知道哪里得自己补。 */
  knownGaps?: string[]
}

const sharedTail = (filePath: string): string => `
写完后**单独一行**输出：${HANDOFF_MARKER}: ${filePath}
写不了文件（没有写工具 / 被沙箱拒绝）就把完整文档贴在回答里并说明原因，别假装写完了。
除此之外不要改任何其它文件，也不要顺手开始新的开发工作。`

/** 第 2 步：动笔前先核对现场。凭记忆写是「转交不全」的头号原因。 */
const fieldCheck = `2) 动笔前先核对现场，**别凭记忆写**（拿不到的写"未核对"，别猜）：
   - 工作区：git status --short / git log --oneline -3 / git branch --show-current
   - 后台：job_list（后台命令）、list_agents（在跑的子代理）、schedule_list（定时任务）
   - 记忆：read_memory（不给关键词），看已经记了什么，别重复记
   - 版本：本机 pin 的包版本、或关键目录的 commit sha`

const infoHeader = (kind: HandoffKind): string => `3) 文档开头先写一个信息头（值没有就写"未知"）：
> 写于 <时间> · 触发方式：${kind === 'rebirth' ? '面板「一键转生」/ agent 工具 handoff_rebirth' : '面板「一键分身」/ agent 工具 handoff_branch'}
> 会话 <短号> · 工作目录 <路径> · 相关版本 <包@版本 / sha>
> 时效：<这份文档里哪些信息很快会过期>`

const styleRules = `5) 写法约束（违反任何一条都算没写完）：
   - 每条结论后面带证据：文件路径（带行号更好）/ 可跑的命令 / 日志或截图在哪
   - 禁用含糊话：「见之前对话」「后面再看」「视情况」「大概差不多了」「跑通即可」。
     "跑通"必须给判据：跑什么命令、输出该是什么
   - 拿不准就写「未确认」；猜错的代价比留空大
   - 被否掉的方案要写下来 + 为什么否；不写，接手者会重试一遍
   - 时间敏感的东西（端口、临时目录、版本号、路径）标明写于何时
   - 篇幅优先给「未完成」和「坑」，别给背景介绍`

const memoryStep = `6) 长期记忆（这套流程的一半价值，别省）：
   调用 record_memory 记 3~5 条，一次一条、自包含：
   - importance 3：会复发的坑 / 被否掉的方案 / 定死的约定；2：用户偏好与称呼；1：一般事实
   - 必记一条指针：这条交接文档的绝对路径 + 一句话主题
   - 已在记忆里的不要重复记；与文档「长期记忆要点」小节保持一致，同一件事不要两处写、更不要两处说法不一样`

const rebirthSections = `## 目标｜这件事最后要变成什么
## 现状（做到哪一步）｜现在的真实状态，不是计划
## 已完成（不要重做）｜每条带证据：文件路径 / 命令 / 能看的东西
## 未完成 / 下一步｜每条必须能直接开工：改哪个文件、跑什么命令、怎么算做完；写不出入口的标「未定位」
## 等用户拍板｜你提了方案没人回、问了没人答的，逐条写清"在等谁、等什么"
## 后台在跑｜后台命令 job id、在跑的子代理、定时任务、没回来的构建：怎么查、怎么收、归谁
## 边界（不要碰的东西）｜用户指定的禁区、别人正在动的文件/目录/任务（没有就写"无"）
## 长期记忆要点｜与第 6 步写进记忆库的条目一致
## 关键决定与理由｜为什么这么定；被否掉的方案 + 否掉的原因
## 坑与教训（踩过的坑、被否掉的方案）｜症状 → 怎么一眼判断 → 怎么绕
## 工作区与版本｜git 分支、未提交改动、未推送提交、盘上并存的半成品目录、pin 的版本/sha
## 相关文件｜绝对路径优先，标清哪个能改、哪个只读`

const branchSections = `## 本体背景（当前这条会话在干什么）
## 交接给分身的长期记忆要点｜与第 6 步写进记忆库的条目一致
## 分支任务（这次要干的新分支）｜用户原文照抄，别转述、别优化
## 边界（不要碰的东西）｜本体正在改的文件/目录 + 本体正在跑的任务
## 后台在跑｜归本体的任务要标"归本体"：分身不许碰、不许收、不许重派
## 关键决定与理由｜为什么这么定；被否掉的方案 + 否掉的原因
## 坑与教训（踩过的坑、被否掉的方案）｜症状 → 怎么一眼判断 → 怎么绕
## 工作区与版本｜git 分支、未提交改动、未推送提交、盘上并存的半成品目录、pin 的版本/sha
## 相关文件｜绝对路径优先，标清哪个能改、哪个只读`

/**
 * 打回补写指令（2026-11-17）：结构判据没过时，把"缺哪几处"发回给前世。
 *
 * 关键写法：**指名小节 + 说要补什么**，不要重发整份指令——重发会让模型从头再写一遍，
 * 把已经写好的东西冲掉。
 */
export function buildFixInstruction(plan: HandoffPlan, problems: string[], round: number): string {
  return `【大肥鱼插件·交接文档待补写（第 ${round} 轮）】
你写的交接文档（${plan.filePath}）过了"文件存在"这一关，但没过**结构判据**。接手者会卡在这些地方：

${problems.map((problem, index) => `${index + 1}. ${problem}`).join('\n')}

请**只补这几处**（用编辑/写文件工具改同一个文件，别重写整份、别改路径、别动已经合格的小节）。
补完再通读一遍：接手者只看这份文档，能不能不用回看这条会话就接着干？

补完后**单独一行**输出：${HANDOFF_MARKER}: ${plan.filePath}
除此之外不要改任何其它文件，也不要开始新的开发工作。`
}

const selfCheck = (kind: HandoffKind): string => `7) 写完**把文件读回来**（read 工具，不是凭记忆），逐节自查核对，缺的立刻补进文件：
   ${kind === 'rebirth'
     ? '目标 / 现状 / 已完成(带证据) / 下一步(可执行) / 等用户拍板 / 后台在跑 / 边界 / 长期记忆 / 决定与理由 / 坑与被否方案 / 工作区与版本 / 相关文件'
     : '本体背景 / 长期记忆要点 / 分支任务(原文) / 边界 / 后台在跑 / 决定与理由 / 坑与被否方案 / 工作区与版本 / 相关文件'}`

/** 发给当前会话的写作指令。 */
export function buildInjection(plan: HandoffPlan): string {
  const title = plan.kind === 'rebirth' ? '一键转生' : '一键分身'
  const who = plan.kind === 'rebirth'
    ? '这条会话马上会因为上下文超载而「转生」：你的活要交给**下一位接手的会话**继续做。'
    : '这条会话要「分身」出一条新的分支会话，去做**另一条分支**的活；本体这条会话继续干原来的事。'
  const note = String(plan.note ?? '').trim()
  const boundary = String(plan.boundary ?? '').trim()
  const extra = plan.kind === 'branch'
    ? `\n【分支任务（用户给的原文，必须原样写进文档的「分支任务」小节，别转述）】\n${note}\n` +
      (boundary
        ? `\n【边界（用户指定，写进「边界（不要碰的东西）」小节）】\n${boundary}\n`
        : '')
    : (note
        ? `\n【用户补充的交接重点（一条不漏地写进文档，漏一条就是没写完）】\n${note}\n`
        : '') +
      (boundary
        ? `【用户指定的边界（写进「边界（不要碰的东西）」小节，接手者不许越线）】\n${boundary}\n`
        : '')

  return `【大肥鱼插件·${title}】
${who}
请你现在写一份**交接文档**，交给接手者。别写客套话，写能直接照着干的东西。
判断标准只有一条：接手者读完，不用回看这条会话、也不用猜，就能接着干。

1) 写文件到这个绝对路径（照抄，不要改路径）：
${plan.filePath}

${fieldCheck}

${infoHeader(plan.kind)}

4) 正文小节，**一节都不许省**，没内容的写"无"：
${plan.kind === 'rebirth' ? rebirthSections : branchSections}
${extra}
${styleRules}

${memoryStep}

${selfCheck(plan.kind)}
${sharedTail(plan.filePath)}`
}

/** 发给新会话的第一句：「读文档 → 核对 → 报到 → 停」，不许开工。 */
export function buildFirstPrompt(plan: HandoffPlan): string {
  const intro = plan.kind === 'rebirth'
    ? '上一个会话因为上下文超载已经转生，你是接手者。'
    : '本体那条会话还在继续原来的工作；你是它的**分身**，负责一条独立的分支任务。'
  const caution = plan.kind === 'rebirth'
    ? '不要修改任何文件，也不要开工。'
    : '本体正在另一条会话里干活：不要碰交接文档「边界」里列出的东西，也不要动「后台在跑」里归本体的任务，' +
      '更不要修改任何文件、不要开工。'
  /*
   * 缺口分流 + 收件箱（2026-11-17）。
   *
   * 老版本的第三件事是「把缺口都报给用户」。真机上的结果是：用户成了人肉传声筒，
   * 来回三轮才补齐——而其中大半缺口本来来生自己就能查（文件现状、git 状态、跑个命令）。
   *
   * 所以这里强制分两类：
   *   · 自查能补的 → 当场查，追加到文档的「补充（来生自查）」小节，不上报；
   *   · 只有前世/用户知道的（当时的取舍、被否原因、在等谁拍板）→ 走收件箱问前世。
   * 收件箱送不到时才退回用户（见 inbox.ts 的 undeliverable 分支）。
   */
  const parent = String(plan.parentSessionId ?? '').trim()
  const inboxStep = parent === ''
    ? `    （这条交接没带前世会话 id，收件箱用不了：这类缺口直接问我。）`
    : `   · 只有前世或用户知道的（当时为什么这么定、被否方案的原因、在等谁拍板）→
     调 handoff_ask 问前世：to="${parent}"，question 写清「你缺什么、要解决什么问题」。
     它的回答会作为新消息送回来，别再让我转达。`
  const gaps = Array.isArray(plan.knownGaps) && plan.knownGaps.length > 0
    ? `
已知缺口（前世补到上限仍未达标，你能自己查的顺手查掉）：
${plan.knownGaps.map((gap, index) => `- ${gap}`).join('\n')}
`
    : ''

  return `${intro}交接文档在这里：

${plan.filePath}

先完整读它，然后**只做四件事，做完就停**：

1) 核对，别只信文档：read_memory 看已经记了什么；文档说"后台在跑"的，
   用 job_list / list_agents / schedule_list 对一下还活着没有；
   说"改了某个文件"的，去读那个文件看现状。
2) 向我报到，三五行：做到哪一步、还有哪些没做、你打算的第一步是什么。
3) 缺口**先自己分拣**，别一股脑丢给我：
   · 你自己能查的（文件现状、git 状态、某个命令的输出）→ 当场查清楚，
     追加到文档的「## 补充（来生自查）」小节，**不要上报**；
${inboxStep}
4) 只有"问了前世也没答上、或者前世不在线"的，才在报到后面单独列「尚未解决的文档缺口」
   （没有就写"无"）。你说没缺口、等我点头开工时才踩空，那就晚了。

${gaps}
${caution}等我点头再动手。`
}

/** 交接文档文件名：`转生-<会话短 id>-<时间戳>.md`。 */
export function handoffFileName(kind: HandoffKind, sessionId: string, at: Date): string {
  const short = sessionId.replace(/^session-/, '').slice(0, 8) || 'unknown'
  const pad = (n: number): string => String(n).padStart(2, '0')
  const stamp =
    `${at.getFullYear()}${pad(at.getMonth() + 1)}${pad(at.getDate())}` +
    `-${pad(at.getHours())}${pad(at.getMinutes())}${pad(at.getSeconds())}`
  return `${kind === 'rebirth' ? '转生' : '分身'}-${short}-${stamp}.md`
}
